// Signs the memory cards in tools/cards.src.js and writes data/cards.js.
//   node tools/build-cards.js                 sign every card, rewrite data/cards.js
//   node tools/build-cards.js --sign card.json [--key council]
//                                             sign your own card file so the phone can verify it
// Private keys live in keys/ (git-ignored). Only the public keys go into data/cards.js.
// Signatures: ECDSA P-256 over SHA-256 of the card's canonical JSON, raw r||s, hex.
'use strict';
const fs = require('fs'), path = require('path'), { webcrypto: crypto } = require('crypto');
const ROOT = path.join(__dirname, '..'), KEYS = path.join(ROOT, 'keys');
const KEY_INFO = {
  council: { name: 'Resident Council', role: 'trusted' },
  ava: { name: 'Ava (L4 Works)', role: 'contact' },
  directorate: { name: 'Directorate', role: 'untrusted' },
};
const canonical = c => JSON.stringify({ id: c.id, title: c.title, issuer: c.issuer, key: c.key, body: c.body });
const hex = b => Buffer.from(b).toString('hex');

async function keyPair(id) {
  fs.mkdirSync(KEYS, { recursive: true });
  const file = path.join(KEYS, id + '.private.jwk');
  if (fs.existsSync(file)) {
    const priv = JSON.parse(fs.readFileSync(file, 'utf8'));
    const pub = { kty: priv.kty, crv: priv.crv, x: priv.x, y: priv.y };
    return { priv: await crypto.subtle.importKey('jwk', priv, { name: 'ECDSA', namedCurve: 'P-256' }, false, ['sign']), pubJwk: pub };
  }
  const kp = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
  const priv = await crypto.subtle.exportKey('jwk', kp.privateKey);
  fs.writeFileSync(file, JSON.stringify(priv));
  const pub = await crypto.subtle.exportKey('jwk', kp.publicKey);
  return { priv: kp.privateKey, pubJwk: { kty: pub.kty, crv: pub.crv, x: pub.x, y: pub.y } };
}
async function signCard(card, k) {
  const s = await crypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, k.priv, Buffer.from(canonical(card)));
  return { ...card, sig: hex(s) };
}

(async () => {
  const args = process.argv.slice(2);
  if (args[0] === '--sign') {
    const card = JSON.parse(fs.readFileSync(args[1], 'utf8'));
    card.key = args.includes('--key') ? args[args.indexOf('--key') + 1] : (card.key || 'council');
    const k = await keyPair(card.key);
    const out = await signCard(card, k);
    const dest = args[1].replace(/\.json$/, '') + '.signed.json';
    fs.writeFileSync(dest, JSON.stringify(out, null, 2));
    console.log('signed with', card.key, '->', dest);
    return;
  }
  const src = require('./cards.src.js'), keys = {};
  for (const id of Object.keys(KEY_INFO)) keys[id] = await keyPair(id);
  const cards = [];
  for (const c of src) cards.push(await signCard(c, keys[c.key]));
  const pub = Object.fromEntries(Object.entries(KEY_INFO).map(([id, info]) => [id, { ...info, jwk: keys[id].pubJwk }]));
  const js = `// GENERATED by tools/build-cards.js. Edit tools/cards.src.js and re-run instead of editing this file.
// Public keys only. Signatures are ECDSA P-256 (SHA-256) over each card's canonical JSON.
window.STRATA_CARDS = ${JSON.stringify({ keys: pub, cards }, null, 1)};
`;
  fs.writeFileSync(path.join(ROOT, 'data', 'cards.js'), js);
  console.log('wrote data/cards.js with', cards.length, 'signed cards');
})().catch(e => { console.error(e); process.exit(1); });
